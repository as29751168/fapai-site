def write_learn(urls):
    write("site/learn.html", learn_index()); urls.append(("/learn", 0.7))
    for s, t, l, secs in LEARN:
        write(f"site/learn/{s}.html", learn_article(s, t, l, secs)); urls.append((f"/learn/{s}", 0.6))

